// ---------------------------------------------------------------------------
// pitchDetection.ts — THE DEVICE'S PITCH PASS, ON THE SERVER (vc62, D26)
//
// WHY THIS FILE EXISTS
// The owner: *"the speed… is too slow… it's almost unusable… there has to be a
// faster way of processing the score."* Measured 11-17: the live route answers a
// 78-second take in 4.07 s, so the NETWORK is not the bottleneck — the phone is.
// `captureMidiExport.ts` then runs `detectPitchFramesAsync` over the whole take:
// ~2,400 YIN period searches for a 60-second take, measured at 4,178 ms of solid
// CPU on a server-class Node process and several times that on a handset's Hermes.
// That is the 15–25 s the owner feels.
//
// WHAT THIS IS: a PORT of the app's own tracker
// (`musicapp-update/src/services/pitchDetection.ts`), frame for frame. It is
// deliberately NOT a second algorithm — the whole point is that the frames this
// produces are the frames the device would have produced, so the client can skip
// its own pass without the notes changing. The golden table in
// `coach-pcm.test.ts` was generated by running the APP's module over the same
// fixture, and the test compares the two.
//
// WHAT IS NOT PORTED, ON PURPOSE: the segmentation half (`segmentsToPlayedNotes`,
// which turns frames into `PlayedNote[]` and depends on the app's scoring types)
// and the UI-yielding async wrapper (`detectPitchFramesAsync` — there is no UI
// thread here to hand back). The server returns FRAMES; the app still does its
// own segmentation from them, exactly as it did before.
//
// Algorithm: YIN-lite (square-difference function, cumulative-mean normalisation,
// parabolic interpolation), on a sliding window with an RMS silence gate.
// ---------------------------------------------------------------------------

/**
 * Analysis window, in samples. 2048 samples ≈ 93 ms at 22.05 kHz — long enough
 * for a stable period estimate down to ~55 Hz, short enough to follow a melody.
 */
export const DEFAULT_WINDOW_SAMPLES = 2048;
/** Frame hop. 25 ms = 40 frames/second — finer than any rhythm tolerance. */
export const DEFAULT_HOP_SECONDS = 0.025;
/** Lowest pitch we will report (A1). */
export const DEFAULT_MIN_FREQ_HZ = 55;
/** Highest pitch we will report (roughly F#6 — above a soprano's top). */
export const DEFAULT_MAX_FREQ_HZ = 1500;
/** RMS silence gate: quieter than this is `midi: null`, not a confident guess. */
export const SILENCE_RMS_THRESHOLD = 0.01;
/** YIN absolute threshold: the first dip below this is taken as the period. */
export const YIN_THRESHOLD = 0.2;
/** When nothing dips below YIN_THRESHOLD, accept the global minimum below this. */
export const YIN_FALLBACK_THRESHOLD = 0.45;

/** MIDI number of A4. */
export const A4_MIDI = 69;
/** Frequency of A4, in Hz. */
export const A4_HZ = 440;

/** One analysis frame: where it starts, what pitch it heard, how loud it was. */
export interface PitchFrame {
  /** Frame START time in seconds (not the window centre). */
  tSec: number;
  /** Detected MIDI note number (float, unrounded) or null when silent/unpitched. */
  midi: number | null;
  /** RMS level of the window. */
  rms: number;
}

export interface PitchDetectionOptions {
  windowSamples?: number;
  hopSeconds?: number;
  minFreqHz?: number;
  maxFreqHz?: number;
  /** RMS below which a frame is silence (default SILENCE_RMS_THRESHOLD). */
  rmsThreshold?: number;
}

interface FrameGrid {
  windowSamples: number;
  hopSamples: number;
  minFreqHz: number;
  maxFreqHz: number;
  rmsThreshold: number;
}

/** Frequency (Hz) → MIDI note number as a float (440 Hz → 69). */
export function hzToMidi(hz: number): number {
  if (!Number.isFinite(hz) || hz <= 0) return Number.NaN;
  return A4_MIDI + 12 * Math.log2(hz / A4_HZ);
}

function clampFreq(value: number | undefined, fallback: number): number {
  if (typeof value !== "number" || !Number.isFinite(value) || value <= 0) return fallback;
  return value;
}

function frameGrid(sampleRate: number, opts: PitchDetectionOptions): FrameGrid {
  const windowSamples = Math.max(64, Math.floor(opts.windowSamples ?? DEFAULT_WINDOW_SAMPLES));
  const hopSeconds = opts.hopSeconds ?? DEFAULT_HOP_SECONDS;
  return {
    windowSamples,
    hopSamples: Math.max(
      1,
      Math.round(
        (Number.isFinite(hopSeconds) ? hopSeconds : DEFAULT_HOP_SECONDS) * sampleRate,
      ),
    ),
    minFreqHz: clampFreq(opts.minFreqHz, DEFAULT_MIN_FREQ_HZ),
    maxFreqHz: clampFreq(opts.maxFreqHz, DEFAULT_MAX_FREQ_HZ),
    rmsThreshold:
      typeof opts.rmsThreshold === "number" && Number.isFinite(opts.rmsThreshold)
        ? opts.rmsThreshold
        : SILENCE_RMS_THRESHOLD,
  };
}

/** Root-mean-square of one window of float samples. */
function rmsOf(samples: Float32Array, start: number, windowSamples: number): number {
  let sum = 0;
  for (let i = 0; i < windowSamples; i++) {
    const s = samples[start + i];
    if (Number.isFinite(s)) sum += s * s;
  }
  return Math.sqrt(sum / windowSamples);
}

/**
 * YIN-lite pitch estimate for one window, as a MIDI number (float) or null.
 * Same steps, same thresholds, same arithmetic as the app's `yinMidi`.
 */
function yinMidi(
  samples: Float32Array,
  start: number,
  windowSamples: number,
  sampleRate: number,
  minFreqHz: number,
  maxFreqHz: number,
): number | null {
  const minLag = Math.max(2, Math.floor(sampleRate / maxFreqHz));
  const maxLag = Math.min(Math.floor(windowSamples / 2), Math.ceil(sampleRate / minFreqHz));
  if (maxLag <= minLag + 1) return null;

  const diff = new Float64Array(maxLag + 1);
  for (let tau = 1; tau <= maxLag; tau++) {
    let sum = 0;
    const count = windowSamples - tau;
    for (let i = 0; i < count; i++) {
      const a = samples[start + i];
      const b = samples[start + i + tau];
      const d = (Number.isFinite(a) ? a : 0) - (Number.isFinite(b) ? b : 0);
      sum += d * d;
    }
    diff[tau] = sum;
  }

  const norm = new Float64Array(maxLag + 1);
  norm[0] = 1;
  let running = 0;
  for (let tau = 1; tau <= maxLag; tau++) {
    running += diff[tau];
    norm[tau] = running <= 0 ? 1 : (diff[tau] * tau) / running;
  }

  let tau = -1;
  for (let t = minLag; t <= maxLag; t++) {
    if (norm[t] < YIN_THRESHOLD) {
      let localMin = t;
      while (localMin + 1 <= maxLag && norm[localMin + 1] < norm[localMin]) localMin++;
      tau = localMin;
      break;
    }
  }
  if (tau < 0) {
    let best = Number.POSITIVE_INFINITY;
    for (let t = minLag; t <= maxLag; t++) {
      if (norm[t] < best) {
        best = norm[t];
        tau = t;
      }
    }
    if (tau < 0 || best > YIN_FALLBACK_THRESHOLD) return null;
  }

  let period = tau;
  if (tau > 1 && tau < maxLag) {
    const a = norm[tau - 1];
    const b = norm[tau];
    const c = norm[tau + 1];
    const denom = 2 * (2 * b - a - c);
    if (denom !== 0) {
      const delta = (c - a) / denom;
      if (Number.isFinite(delta) && Math.abs(delta) < 1) period = tau + delta;
    }
  }
  if (!Number.isFinite(period) || period <= 0) return null;

  const hz = sampleRate / period;
  if (!Number.isFinite(hz) || hz < minFreqHz * 0.9 || hz > maxFreqHz * 1.1) return null;
  return hzToMidi(hz);
}

function frameAt(
  samples: Float32Array,
  start: number,
  grid: FrameGrid,
  sampleRate: number,
): PitchFrame {
  const rms = rmsOf(samples, start, grid.windowSamples);
  const midi =
    rms < grid.rmsThreshold
      ? null
      : yinMidi(samples, start, grid.windowSamples, sampleRate, grid.minFreqHz, grid.maxFreqHz);
  return { tSec: start / sampleRate, midi, rms };
}

/**
 * Track monophonic pitch across a recording, one frame per hop.
 *
 * Frames sit on an absolute grid from sample 0 (`tSec = start / sampleRate`), only
 * whole windows are analysed, and a frame the tracker is not confident about comes
 * back `midi: null` — an honest no-match beats a wrong note, the same rule the
 * recognition surfaces follow.
 */
export function detectPitchFrames(
  samples: Float32Array,
  sampleRate: number,
  opts: PitchDetectionOptions = {},
): PitchFrame[] {
  const frames: PitchFrame[] = [];
  if (!samples || samples.length === 0) return frames;
  if (!Number.isFinite(sampleRate) || sampleRate <= 0) return frames;

  const grid = frameGrid(sampleRate, opts);
  const total = samples.length;
  if (total < grid.windowSamples) return frames;

  for (let start = 0; start + grid.windowSamples <= total; start += grid.hopSamples) {
    frames.push(frameAt(samples, start, grid, sampleRate));
  }
  return frames;
}

/**
 * TRUE WHEN THESE FRAMES HOLD NO MELODY — i.e. not one frame was confidently
 * pitched. Used by the route's own test and by any caller that wants to tell "the
 * take was silent" from "the take was music".
 */
export function framesHoldNoMelody(frames: ReadonlyArray<PitchFrame> | null | undefined): boolean {
  const list = Array.isArray(frames) ? frames : [];
  for (const frame of list) {
    if (typeof frame?.midi === "number" && Number.isFinite(frame.midi)) return false;
  }
  return true;
}
